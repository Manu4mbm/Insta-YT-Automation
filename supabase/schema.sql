-- optional: paid guides / kits (Razorpay payment links or UPI)
create table if not exists public.products (
  slug text primary key, title text not null, description text, price_paise integer not null,
  kit_path text, active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  product_slug text not null references public.products(slug),
  email text not null, phone text not null default '',
  price_paise integer not null, amount_paise integer not null,
  status text not null default 'pending',
  token text not null default encode(gen_random_bytes(18), 'hex'),
  utr text, alert_id text, claimed_utr text,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '20 minutes'),
  paid_at timestamptz, mailed_at timestamptz, downloads integer not null default 0,
  provider text not null default 'upi', rp_order_id text, rp_payment_id text, rp_link_url text
);
create index if not exists orders_pending_amount on public.orders (amount_paise, created_at) where status = 'pending';
create unique index if not exists orders_rp_order on public.orders (rp_order_id) where rp_order_id is not null;
create table if not exists public.pay_alerts (
  id text primary key, from_addr text, subject text, amount_paise integer, utr text,
  received_at timestamptz not null, matched_order uuid references public.orders(id), note text,
  created_at timestamptz not null default now()
);
create index if not exists pay_alerts_utr on public.pay_alerts (utr);

