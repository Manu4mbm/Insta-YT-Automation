-- per-slot analytics (which posting time works best)
create or replace view public.slot_performance with (security_invoker = true) as
select p.reel_slug,
  to_char(p.published_at at time zone 'Asia/Kolkata', 'Dy DD Mon') as day,
  to_char(p.published_at at time zone 'Asia/Kolkata', 'HH24:MI') as slot,
  m.age_h, m.views, m.reach, m.shares, m.saved, m.comments, m.likes,
  round(m.avg_watch_ms::numeric / 1000.0, 1) as avg_watch_s,
  round(100.0 * m.shares::numeric / nullif(m.reach, 0)::numeric, 2) as share_pct,
  round(100.0 * m.saved::numeric / nullif(m.reach, 0)::numeric, 2) as save_pct
from public.post_metrics m join public.posts p on p.id = m.post_id;

-- payment helpers (used by api/pay) -------------------------------------------
create or replace function public.pay_create_order(p_slug text, p_email text, p_phone text)
returns public.orders language plpgsql security definer set search_path to 'public' as $function$
declare o public.orders; v_price int; v_off int;
begin
  perform pg_advisory_xact_lock(4949);
  select * into o from orders where product_slug = p_slug and email = p_email and status = 'pending' and expires_at > now()
    order by created_at desc limit 1;
  if found then return o; end if;
  select price_paise into v_price from products where slug = p_slug and active;
  if v_price is null then raise exception 'no_product'; end if;
  select off into v_off from generate_series(1, 399) off
   where v_price - off >= 100
     and not exists (select 1 from orders x where x.status = 'pending' and x.amount_paise = v_price - off and x.created_at > now() - interval '60 minutes')
   order by off limit 1;
  if v_off is null then raise exception 'busy'; end if;
  insert into orders (product_slug, email, phone, price_paise, amount_paise)
    values (p_slug, p_email, p_phone, v_price, v_price - v_off) returning * into o;
  return o;
end $function$;

create or replace function public.pay_match_alert(p_alert text)
returns uuid language plpgsql security definer set search_path to 'public' as $function$
declare a public.pay_alerts; v_id uuid;
begin
  perform pg_advisory_xact_lock(4950);
  select * into a from pay_alerts where id = p_alert;
  if a.id is null or a.matched_order is not null or a.amount_paise is null then return a.matched_order; end if;
  select id into v_id from orders
   where status = 'pending' and amount_paise = a.amount_paise
     and created_at between a.received_at - interval '75 minutes' and a.received_at + interval '2 minutes'
   order by created_at desc limit 1;
  if v_id is null then return null; end if;
  update orders set status = 'paid', paid_at = now(), utr = a.utr, alert_id = a.id where id = v_id;
  update pay_alerts set matched_order = v_id where id = a.id;
  return v_id;
end $function$;

create or replace function public.pay_claim_utr(p_order uuid, p_utr text)
returns text language plpgsql security definer set search_path to 'public' as $function$
declare o public.orders; a public.pay_alerts;
begin
  perform pg_advisory_xact_lock(4950);
  select * into o from orders where id = p_order;
  if o.id is null then return 'no_order'; end if;
  if o.status = 'paid' then return 'paid'; end if;
  update orders set claimed_utr = p_utr where id = o.id;
  select * into a from pay_alerts where utr = p_utr limit 1;
  if a.id is null then return 'not_seen'; end if;
  if a.matched_order is not null then return 'used'; end if;
  if a.amount_paise < o.amount_paise then return 'low'; end if;
  if a.received_at < o.created_at - interval '10 minutes' then return 'old'; end if;
  update orders set status = 'paid', paid_at = now(), utr = a.utr, alert_id = a.id where id = o.id;
  update pay_alerts set matched_order = o.id where id = a.id;
  return 'paid';
end $function$;
revoke all on function public.pay_create_order(text,text,text), public.pay_match_alert(text), public.pay_claim_utr(uuid,text) from public, anon, authenticated;
