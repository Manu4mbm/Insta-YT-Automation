create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  reel_slug text not null,
  video_url text not null,
  cover_url text,
  caption text not null,
  keyword text,
  scheduled_at timestamptz not null,
  status text not null default 'queued',          -- queued | publishing | published | error
  container_id text,
  ig_media_id text,
  error text,
  attempts integer not null default 0,
  published_at timestamptz,
  created_at timestamptz default now(),
  first_comment text,
  first_comment_id text,
  trial_strategy text,                              -- e.g. 'SS_PERFORMANCE' = post as trial reel
  auto_paid jsonb                                   -- {views, product, dm_text, done}
);
create index if not exists posts_due_idx on public.posts (status, scheduled_at);
create index if not exists posts_ig_media_idx on public.posts (ig_media_id);

create table if not exists public.dm_rules (
  id uuid primary key default gen_random_uuid(),
  post_id uuid references public.posts(id) on delete cascade,
  keyword text not null,
  dm_text text not null,
  public_reply text default 'DM check karo 📩',
  active boolean not null default true,
  created_at timestamptz default now(),
  follow_gate boolean not null default true,
  gate_text text,
  any_comment boolean not null default true
);
create index if not exists dm_rules_post_idx on public.dm_rules (post_id);

create table if not exists public.dm_log (
  comment_id text primary key,
  ig_user_id text,
  post_id uuid references public.posts(id) on delete set null,
  keyword text,
  sent_at timestamptz default now(),
  ok boolean,
  error text,
  rule_id uuid references public.dm_rules(id) on delete set null,
  status text not null default 'gated',
  gate_attempts integer not null default 0,
  delivered_at timestamptz,
  poll_seen_at timestamptz,
  follow_checked_at timestamptz,
  follow_nudged_at timestamptz,
  retries integer not null default 0,
  public_replied_at timestamptz
);
create index if not exists dm_log_user_status_idx on public.dm_log (ig_user_id, status, sent_at desc);
create index if not exists dm_log_public_replied_at_idx on public.dm_log (public_replied_at);

create table if not exists public.settings (key text primary key, value text, updated_at timestamptz default now());

create table if not exists public.send_log (id bigint generated by default as identity primary key, at timestamptz not null default now(), kind text not null);
create index if not exists send_log_at_idx on public.send_log (at);

create table if not exists public.post_metrics (
  post_id uuid not null references public.posts(id) on delete cascade,
